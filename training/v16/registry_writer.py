"""Story AI v16 registry-backed scene composer. No training required.

The registry supplies exact character references. The model (if requested) only
suggests a short sensory detail; it cannot directly write/change cast or events.
All accepted model contributions are attributed in the report.
"""
from __future__ import annotations

import argparse
import copy
import json
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any


class StoryError(ValueError):
    pass


def whole_word_count(text: str, word: str) -> int:
    return len(re.findall(r"(?<!\w)" + re.escape(word) + r"(?!\w)", text, re.I))


def validate_story(story: dict) -> None:
    people = story.get('characters')
    if not isinstance(people, dict) or not people:
        raise StoryError('characters must be a nonempty dictionary keyed by character ID')
    seen = set()
    for cid, character in people.items():
        if not re.fullmatch(r'[a-z][a-z0-9_]*', cid):
            raise StoryError(f'invalid character ID: {cid}')
        name = character.get('name', '')
        if not isinstance(name, str) or not re.fullmatch(r"[A-Za-z][A-Za-z' -]{0,47}", name):
            raise StoryError(f'invalid character name for {cid}: {name!r}')
        if name.lower() in seen:
            raise StoryError('duplicate character name')
        seen.add(name.lower())
    if not isinstance(story.get('beats'), list) or not story['beats']:
        raise StoryError('beats must be a nonempty list')
    if len({b.get('id') for b in story['beats']}) != len(story['beats']):
        raise StoryError('beat ids must be unique')


def safe_text(text: str, field: str) -> str:
    if not isinstance(text, str) or not text.strip():
        raise StoryError(f'{field} must contain nonempty text')
    if re.search(r'[\r\n]', text):
        raise StoryError(f'{field} cannot include line breaks')
    return text.strip()


def ensure_actor(people: dict, cid: str) -> str:
    if cid not in people:
        raise StoryError(f'Unknown character id {cid!r}. Add to registry explicitly.')
    return people[cid]['name']


def sentence(text: str) -> str:
    text = text.strip()
    return text if text[-1:] in '.!?' else text + '.'


def render_beat(beat: dict, people: dict) -> str:
    """Render only explicit story events; no name guessing or model-authored actions."""
    kind = beat.get('type')
    actor = ensure_actor(people, beat.get('actor'))
    if kind == 'action':
        # Literal action is supplied by author, not generated by the model.
        action = safe_text(beat.get('action'), 'action')
        return sentence(f'{actor} {action}')
    if kind == 'dialogue':
        quote = safe_text(beat.get('quote'), 'quote').strip('“”"')
        tag = beat.get('tag', 'said')
        if tag not in {'said', 'whispered', 'asked', 'answered', 'warned', 'replied'}:
            raise StoryError('invalid dialogue tag')
        quote = quote.rstrip(' .!?') + (quote[-1] if quote.endswith(('?', '!')) else ',')
        return f'“{quote}” {actor} {tag}.'
    if kind == 'interaction':
        other = ensure_actor(people, beat.get('with'))
        if other == actor:
            raise StoryError('interaction actor and with must be distinct')
        action = safe_text(beat.get('action'), 'action')
        return sentence(f'{actor} {action} {other}')
    if kind == 'observation':
        observation = safe_text(beat.get('observation'), 'observation')
        return sentence(f'{actor} noticed {observation}')
    raise StoryError(f'unsupported beat type {kind!r}')


# Ordinary sentence-initial words should not be confused with new people.
# This filter is intentionally strict: it can reject legitimate descriptions,
# but it never rewrites a character name.
ALLOWED_CAPS = set('A An The And But Or Yet As When While Then There It Its In On At From Under Above Beyond Behind Before After Near By Of To This That These Those Nothing Something One Two Three No Yes Never Rain Wind Moon Light Darkness Silence Footsteps Water Stone Iron Somewhere Nothing'.split())

def validate_detail(detail: str, story: dict, recent_details: list[str]) -> list[str]:
    reasons = []
    if not detail or len(detail) > 180:
        reasons.append('detail missing or too long')
    # A single capital, ellipsis, or a short fragment is not a usable atmospheric detail.
    words = re.findall(r"[A-Za-z]+(?:['’][A-Za-z]+)?", detail)
    if len(words) < 5 or len(detail.strip()) < 25:
        reasons.append('detail is too short to be a complete descriptive sentence')
    if re.search(r'\.{2,}|…|[\[\]{}<>]', detail):
        reasons.append('detail contains ellipsis or markup')
    if re.fullmatch(r'\s*(?:[A-Za-z]\s*\.|[.?!…\s]+)\s*', detail):
        reasons.append('detail is an initial or punctuation-only fragment')
    if '\n' in detail or '"' in detail or '“' in detail or '”' in detail:
        reasons.append('detail contains dialogue or line break')
    if not re.search(r'[.!?]$', detail):
        reasons.append('detail must end with punctuation')
    if re.search(r'\b(CHAPTER|Story so far|Continuation|Characters to preserve)\b', detail, re.I):
        reasons.append('prompt or chapter contamination')
    # Neither known names nor unknown titlecase names are permitted in detail slots.
    for char in story['characters'].values():
        if whole_word_count(detail, char['name']):
            reasons.append('detail contains a registered character')
    for token in re.findall(r'\b[A-Z][a-z]{2,}\b', detail):
        if token not in ALLOWED_CAPS:
            reasons.append('possible name or unsupported proper noun: ' + token)
    if detail.casefold() in [d.casefold() for d in recent_details]:
        reasons.append('repeated descriptive detail')
    forbidden = story.get('forbidden_phrases', [])
    if any(term.casefold() in detail.casefold() for term in forbidden):
        reasons.append('forbidden event referenced')
    # Sensory-only details must not introduce new agents or assert plot-changing events.
    if re.search(r'\b(he|she|they|him|her|their|someone|somebody|man|woman|boy|girl|person|stranger|guard|soldier|opened|entered|left|escaped|killed|died|found)\b', detail, re.I):
        reasons.append('possible unapproved actor or action')
    return sorted(set(reasons))


@dataclass
class DetailGenerator:
    checkpoint: str
    tokenizer_path: str
    device: str
    seed: int
    prompt_style: str = 'continuation'
    def __post_init__(self):
        import torch
        from tokenizers import Tokenizer
        from training.v15.model import GPT, GPTConfig
        self.torch = torch
        self.tok = Tokenizer.from_file(self.tokenizer_path)
        ckpt = torch.load(self.checkpoint, map_location='cpu', weights_only=False)
        self.model = GPT(GPTConfig(**ckpt['model_config'])).to(self.device)
        self.model.load_state_dict(ckpt['model'], strict=True)
        self.model.eval()
        self.index = 0

    def generate(self, location: str, previous: str, max_tokens: int) -> str:
        """Return one candidate detail and retain the raw model output for audit.

        Continuation prompt echoes the model's SFT format; it is NOT a new
        learned capability and does not guarantee a useful description.
        """
        if self.prompt_style == 'continuation':
            prompt = (
                'Continue the following fiction scene naturally, preserving its characters, point of view, and events.\n\n'
                'Story so far:\n'
                f'{previous}\n\n'
                'Continuation:\n'
            )
        elif self.prompt_style == 'instruction':
            prompt = (
                'Describe the atmosphere of the following scene in one short sentence. '
                'Do not mention people, names, or actions.\n\n'
                f'Location: {location}\n'
                f'Previous sentence: {previous}\n'
                'Atmosphere: '
            )
        else:
            raise StoryError('invalid prompt style: ' + self.prompt_style)
        ids = self.tok.encode(prompt).ids
        block_size = getattr(self.model.config, 'block_size', 1024) if hasattr(self.model, 'config') else 1024
        if len(ids) + max_tokens > block_size:
            raise StoryError('generation prompt and output exceed model context limit')
        x = self.torch.tensor([ids], dtype=self.torch.long, device=self.device)
        self.torch.manual_seed(self.seed + self.index)
        self.index += 1
        with self.torch.inference_mode():
            out = self.model.generate(x, max_new_tokens=max_tokens, temperature=0.65, top_k=30)
        raw = self.tok.decode(out[0].tolist()[len(ids):], skip_special_tokens=True).strip()
        self.last_generation = {'prompt_style': self.prompt_style, 'prompt': prompt, 'raw_output': raw}
        # Only one sentence may enter the separate sensory-detail validator.
        # Preserve the entire raw generation in last_generation; never silently
        # replace it with fixed story text.
        sentence_match = re.search(r'[^\n.!?]+[.!?](?=\s|$)', raw)
        return sentence_match.group(0).strip() if sentence_match else raw


def generate_story(story: dict, model: Any = None, detail_tokens: int = 32) -> dict:
    """Stateless and deterministic for a given model/seed; verifies before saving."""
    validate_story(story)
    state = copy.deepcopy(story.get('initial_state', {}))
    location = safe_text(story.get('location'), 'location')
    lines, trace, inserted_details, mentioned = [], [], [], set()
    for i, beat in enumerate(story['beats']):
        # Do not commit any state mutation until beat is successfully rendered.
        line = render_beat(beat, story['characters'])
        actor_ids = [beat['actor']] + ([beat['with']] if beat['type'] == 'interaction' else [])
        mentioned.update(actor_ids)
        forbidden = story.get('forbidden_phrases', [])
        if any(term.casefold() in line.casefold() for term in forbidden):
            raise StoryError('beat violates forbidden event: ' + beat['id'])
        changes = beat.get('set_state', {})
        if not isinstance(changes, dict) or any(not isinstance(k, str) for k in changes):
            raise StoryError('set_state must be an object')
        # Author-controlled state changes, no inferred plot updates.
        lines.append(line)
        detail_info = {'status': 'not_requested', 'raw': None, 'reasons': []}
        if model is not None and beat.get('atmosphere', False):
            raw = model.generate(location, line, detail_tokens)
            reasons = validate_detail(raw, story, inserted_details)
            detail_info = {'status': 'rejected' if reasons else 'accepted', 'raw': raw, 'reasons': reasons}
            if isinstance(getattr(model, 'last_generation', None), dict):
                detail_info['model_debug'] = copy.deepcopy(model.last_generation)
            if not reasons:
                lines.append(raw)
                inserted_details.append(raw)
        state.update(changes)
        trace.append({'beat_id': beat['id'], 'line': line, 'detail': detail_info, 'state_after': copy.deepcopy(state)})
    required = story.get('required_characters', list(story['characters']))
    if any(cid not in mentioned for cid in required):
        raise StoryError('A required character is absent from the planned beats')
    text = '\n\n'.join(lines)
    counts = {char['name']: whole_word_count(text, char['name']) for char in story['characters'].values()}
    return {'mode': 'registry_composed', 'text': text, 'character_mentions': counts,
            'ai_detail_count': len(inserted_details), 'total_beats': len(trace),
            'generated_full_scene_by_model': False,
            'state': state, 'trace': trace,
            'note': 'Character names and plot actions come from the structured story plan. Only accepted sensory details may come from the model.'}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--scene', required=True)
    p.add_argument('--checkpoint', default=None)
    p.add_argument('--tokenizer', default='dataset/v15_prose_expanded/tokenizer.json')
    p.add_argument('--device', default='cpu')
    p.add_argument('--seed', type=int, default=42)
    p.add_argument('--detail-tokens', type=int, default=32)
    p.add_argument('--prompt-style', choices=['continuation', 'instruction'], default='continuation')
    p.add_argument('--output', default='reports/v16_registry_writer.json')
    p.add_argument('--text-output', default=None)
    p.add_argument('--state-in', default=None, help='JSON state saved by earlier scene')
    p.add_argument('--state-out', default=None, help='Write verified next-scene state')
    a = p.parse_args()
    story = json.loads(Path(a.scene).read_text(encoding='utf8'))
    if a.state_in:
        previous = json.loads(Path(a.state_in).read_text(encoding='utf8'))
        if not isinstance(previous, dict):
            raise StoryError('state-in must contain a JSON object')
        story['initial_state'] = previous
    model = DetailGenerator(a.checkpoint, a.tokenizer, a.device, a.seed, a.prompt_style) if a.checkpoint else None
    result = generate_story(story, model, a.detail_tokens)
    out = Path(a.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding='utf8')
    if a.state_out:
        state_out = Path(a.state_out)
        state_out.parent.mkdir(parents=True, exist_ok=True)
        state_out.write_text(json.dumps(result['state'], ensure_ascii=False, indent=2), encoding='utf8')
    if a.text_output:
        txt = Path(a.text_output)
        txt.parent.mkdir(parents=True, exist_ok=True)
        txt.write_text(result['text'] + '\n', encoding='utf8')
    print(result['text'])
    print('\nACCEPTED MODEL DETAILS:', result['ai_detail_count'])
    print('CHARACTER COUNTS:', result['character_mentions'])
    print('SAVED:', out)

if __name__ == '__main__':
    main()
